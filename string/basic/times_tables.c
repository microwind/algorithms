#include <stdio.h>
#include <stdlib.h>

/**
 * ================================================
 * 程序名称：九九乘法表（上三角形式）
 * 功能描述：打印从 1 到 num-1 的上三角乘法表
 *            只打印 i <= j 的部分（避免重复）
 * 作者：升级优化版
 * 日期：2026年4月
 * ================================================
 *
 * 输出示例（num = 10）：
 * 1 * 1 = 1   1 * 2 = 2   1 * 3 = 3   ... 1 * 9 = 9
 * 2 * 2 = 4   2 * 3 = 6   2 * 4 = 8   ... 2 * 9 = 18
 * 3 * 3 = 9   3 * 4 = 12  ... 
 * ...
 * 9 * 9 = 81
 * ================================================
 */

/**
 * times_table1 - 使用 for 循环实现乘法表（推荐版本）
 * @param num 打印到 num-1 的乘法表（例如传入10，打印1~9）
 * 
 * 特点：结构清晰，易读，效率高
 */
void times_table1(int num)
{
    printf("=== 九九乘法表 (for循环版本) ===\n");

    for (int i = 1; i < num; i++) {
        printf("\n");                    // 每行开始换行
        
        for (int j = 1; j < num; j++) {  // j 从1开始
            if (i <= j) {                // 只打印上三角部分 (i <= j)
                // %2d 和 %3d 用于对齐输出，使结果更美观
                printf("%2d * %2d = %3d   ", i, j, i * j);
            }
        }
    }
    printf("\n\n");
}

/**
 * times_table2 - 使用 while 循环实现乘法表（原始风格）
 * @param num 打印到 num-1 的乘法表
 * 
 * 特点：保留了 while 循环写法，用于教学对比
 */
void times_table2(int num)
{
    printf("=== 九九乘法表 (while循环版本) ===\n");

    for (int i = 1; i < num; i++) {
        printf("\n");
        int j = 1;
        
        while (j < num) {
            if (i <= j) {
                printf("%2d * %2d = %3d   ", i, j, i * j);
            }
            j++;
        }
    }
    printf("\n\n");
}

/**
 * 更优化的推荐版本
 */
void times_table3(int num)
{
    printf("=== 九九乘法表 (最优版本 - 推荐) ===\n");

    for (int i = 1; i < num; i++) {
        printf("\n");
        // 内层循环直接从 i 开始，无需 if 判断，效率最高
        for (int j = i; j < num; j++) {
            printf("%2d × %2d = %3d   ", i, j, i * j);
        }
    }
    printf("\n\n");
}

int main()
{
    printf("九九乘法表演示程序\n");
    printf("================================\n\n");


    times_table1(10);
    
    times_table2(10);
    
    times_table3(10);

    printf("程序结束。\n");
    return 0;
}
